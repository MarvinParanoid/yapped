/**
 * The shape of `en`, with every leaf widened from its literal back to `string`
 * — otherwise a translation would have to repeat the English word to typecheck.
 * Structure is still enforced: a missing or misspelled key fails the build.
 */
type Widen<T> = { [K in keyof T]: T[K] extends string ? string : Widen<T[K]> };

